#!/usr/bin/env python3
# Generates config/starship/custom/pastel-powerline{,.cap}.toml — supershell's
# ready-made prompt settings (the default since v0.1.0).
# Glyphs are written from their code points (never typed), so none can get lost.
#   python3 scripts/gen-custom-prompt.py
import os
import sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ARROW = chr(0xE0B0)  # powerline arrow: the separator pastel-powerline itself uses
LCAP = chr(0xE0B6)   # left half circle: the preset's rounded start (only with `prompt cap on`)

# pastel-powerline's own colours, left to right
PURPLE, PINK, ORANGE, LBLUE, TEAL, BLUE = "#9A348E", "#DA627D", "#FCA17D", "#86BBD8", "#06969A", "#33658A"
LANGS = ["$c", "$elixir", "$elm", "$golang", "$gradle", "$haskell", "$java", "$julia",
         "$maven", "$nodejs", "$bun", "$nim", "$rust", "$scala"]


def fmt(cap):
    lines = [f"[{LCAP}](fg:{PURPLE})\\"] if cap else []
    lines += [
        "$os\\", "$username\\",
        f"[{ARROW}](bg:{PINK} fg:{PURPLE})\\",
        "$directory\\",
        f"[{ARROW}](fg:{PINK} bg:{ORANGE})\\",
        "$git_branch\\", "$git_status\\",
        f"[{ARROW}](fg:{ORANGE} bg:{LBLUE})\\",
        *[f"{m}\\" for m in LANGS],
        f"[{ARROW}](fg:{LBLUE} bg:{TEAL})\\",
        "$docker_context\\",
        f"[{ARROW}](fg:{TEAL} bg:{BLUE})\\",
        "$fill\\",      # the last colour runs to the right edge of the window
        "$time\\",      # the clock sits at the right edge; the line ends square
        "$line_break\\",
        '$kubernetes$cmd_duration$jobs$status$character"""',
    ]
    return 'format = """\n' + "\n".join(lines)


HEAD = """# supershell's ready-made prompt settings for the pastel-powerline style{variant}.
# GENERATED by scripts/gen-custom-prompt.py — edit that script, not this file.
# The default (`prompt_custom = on`); `supershell prompt custom off` = the preset exactly
# as starship publishes it. Applied on top of starship's preset; values here win. Your
# own ~/.config/supershell/prompt.toml still wins over this file.
#
# Same look as the preset (its colours and {arrow} arrows); the differences, all plain
# starship settings:
#   - the bar spans the whole terminal width: the last colour fills up to the right
#     edge (`$fill`), with the clock at the right; the line ends square;
#   - {start};
#   - kubernetes context, command duration and exit status move to the second line,
#     in front of the ❯ (the first line is full);
#   - a space before your name inside the first colour.
"""

TAIL = f"""
[username]
format = '[ $user ]($style)'

[fill]
symbol = " "
style = "bg:{BLUE}"

[line_break]
disabled = false
"""

for cap, name in ((False, "pastel-powerline.toml"), (True, "pastel-powerline.cap.toml")):
    head = HEAD.format(
        variant=" — square start (default)" if cap is False else " — rounded start (`supershell prompt cap on`)",
        arrow=ARROW,
        start=("the line starts square at the left edge of the window" if not cap
               else f"the line starts with the preset's rounded edge ({LCAP})"),
    )
    with open(os.path.join(ROOT, "config/starship/custom", name), "w") as f:
        f.write(head + "\n" + fmt(cap) + "\n" + TAIL)
print("written")
